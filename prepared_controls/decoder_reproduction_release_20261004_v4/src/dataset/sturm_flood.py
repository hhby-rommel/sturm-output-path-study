"""PyTorch input pipeline for the audited STURM-Flood tiles.

The loader keeps native sensor channels (S1=2, S2=9) and exposes an explicit
valid-pixel mask.  It does not silently pad or truncate channels: mixed-sensor
samples must be routed through a sensor adapter before they can be batched.
"""

from __future__ import annotations

import csv
from pathlib import Path
from typing import Any, Iterable

import numpy as np
import rasterio
import torch
from torch.utils.data import DataLoader, Dataset

from .quality import quality_badness, quality_vector


DEFAULT_IGNORE_INDEX = 255
SENSOR_INDEX = {"S1": 0, "S2": 1}


def _read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def _parse_nodata(value: str | float | None) -> float | None:
    if value is None or value == "":
        return None
    parsed = float(value)
    return parsed if np.isfinite(parsed) else None


def _valid_pixels(image: np.ndarray, nodata: float | None) -> np.ndarray:
    """Apply the project protocol: finite in every channel and no image nodata."""
    valid = np.isfinite(image).all(axis=0)
    if nodata is not None and np.isfinite(nodata):
        valid &= ~(image == nodata).any(axis=0)
    return valid


class SturmFloodDataset(Dataset[dict[str, Any]]):
    """Read manifest-referenced image/mask tiles without changing raw files.

    Args:
        manifest_path: Canonical tile manifest generated by the full audit.
        split_path: Event assignment CSV.  If supplied, ``split`` is required.
        split: One of ``train``, ``val`` or ``test``.
        sensor: Optional native sensor filter (``S1`` or ``S2``).
        ignore_index: Target value assigned to invalid pixels.
    """

    def __init__(
        self,
        manifest_path: str | Path,
        split_path: str | Path | None = None,
        split: str | None = None,
        sensor: str | None = None,
        ignore_index: int = DEFAULT_IGNORE_INDEX,
    ) -> None:
        self.manifest_path = Path(manifest_path).resolve()
        self.project_root = self.manifest_path.parents[2]
        self.ignore_index = int(ignore_index)

        rows = _read_csv(self.manifest_path)
        if split_path is not None:
            if split is None:
                raise ValueError("split must be provided when split_path is used")
            assignments = {
                row["event_id"]: row["split"]
                for row in _read_csv(Path(split_path).resolve())
            }
            missing = sorted({row["event_id"] for row in rows} - set(assignments))
            if missing:
                raise ValueError(f"split file misses event IDs, first={missing[:3]}")
            rows = [row for row in rows if assignments[row["event_id"]] == split]
            self.split = split
        else:
            self.split = None

        if sensor is not None:
            sensor = sensor.upper()
            if sensor not in SENSOR_INDEX:
                raise ValueError(f"sensor must be S1 or S2, got {sensor!r}")
            rows = [row for row in rows if row["sensor"].upper() == sensor]
        self.sensor = sensor
        self.rows = rows

        if not self.rows:
            raise ValueError("dataset selection is empty")

    def __len__(self) -> int:
        return len(self.rows)

    def _path(self, relative_path: str) -> Path:
        path = self.project_root / "data" / "raw" / "Dataset" / relative_path
        if not path.exists():
            raise FileNotFoundError(path)
        return path

    def __getitem__(self, index: int) -> dict[str, Any]:
        row = self.rows[index]
        image_path = self._path(row["image_path"])
        mask_path = self._path(row["mask_path"])

        with rasterio.open(image_path) as image_ds:
            image = image_ds.read()
            image_nodata = image_ds.nodata
            image_shape = (image_ds.height, image_ds.width)
        with rasterio.open(mask_path) as mask_ds:
            raw_mask = mask_ds.read(1)
            mask_nodata = mask_ds.nodata
            mask_shape = (mask_ds.height, mask_ds.width)

        if image.shape[1:] != image_shape or mask_shape != image_shape:
            raise ValueError(
                f"shape mismatch for {row['tile_id']}: image={image.shape}, mask={mask_shape}"
            )
        if raw_mask.shape != image.shape[1:]:
            raise ValueError(
                f"mask shape mismatch for {row['tile_id']}: image={image.shape}, mask={raw_mask.shape}"
            )

        valid = _valid_pixels(image, image_nodata)
        mask_valid = np.isfinite(raw_mask)
        if mask_nodata is not None and np.isfinite(mask_nodata):
            mask_valid &= raw_mask != mask_nodata
        valid &= mask_valid

        # The model input must be finite.  The valid mask retains the exact
        # exclusion boundary so loss/metrics can ignore the replacement pixels.
        image = np.nan_to_num(
            image.astype(np.float32, copy=False),
            nan=0.0,
            posinf=0.0,
            neginf=0.0,
        )
        binary_mask = (raw_mask > 0).astype(np.int64, copy=False)
        target = binary_mask.copy()
        target[~valid] = self.ignore_index
        quality = quality_vector(
            image,
            row["sensor"],
            nodata_value=image_nodata,
            saturation_range=None,
        )
        quality_values = np.asarray(
            [quality[name] for name in ("valid_pixel_ratio", "nodata_ratio", "saturation_ratio", "sensor_specific_noise_index")],
            dtype=np.float32,
        )
        quality_available = np.asarray(
            [
                1.0,
                1.0,
                quality["saturation_ratio_available"],
                quality["sensor_specific_noise_index_available"],
            ],
            dtype=np.float32,
        )

        return {
            "image": torch.from_numpy(np.ascontiguousarray(image)),
            "mask": torch.from_numpy(np.ascontiguousarray(target)),
            "valid_mask": torch.from_numpy(np.ascontiguousarray(valid)),
            "raw_mask": torch.from_numpy(np.ascontiguousarray(raw_mask.astype(np.int64, copy=False))),
            "sensor_index": torch.tensor(SENSOR_INDEX[row["sensor"].upper()], dtype=torch.long),
            "quality": torch.from_numpy(quality_values),
            "quality_available": torch.from_numpy(quality_available),
            "quality_score": torch.tensor(quality_badness(quality), dtype=torch.float32),
            "sensor": row["sensor"],
            "event_id": row["event_id"],
            "tile_id": row["tile_id"],
        }


def sturm_collate(batch: Iterable[dict[str, Any]]) -> dict[str, Any]:
    """Collate same-sensor samples and reject mixed native channel counts."""
    items = list(batch)
    if not items:
        raise ValueError("cannot collate an empty batch")
    sensors = {item["sensor"] for item in items}
    channels = {int(item["image"].shape[0]) for item in items}
    if len(sensors) != 1 or len(channels) != 1:
        raise ValueError(
            "native S1/S2 samples cannot share a tensor batch; "
            "group by sensor and apply the corresponding sensor-specific input adapter first "
            f"(sensors={sorted(sensors)}, channels={sorted(channels)})"
        )

    tensor_keys = (
        "image",
        "mask",
        "valid_mask",
        "raw_mask",
        "sensor_index",
        "quality",
        "quality_available",
        "quality_score",
    )
    result: dict[str, Any] = {
        key: torch.stack([item[key] for item in items], dim=0) for key in tensor_keys
    }
    result.update(
        {
            "sensor": [item["sensor"] for item in items],
            "event_id": [item["event_id"] for item in items],
            "tile_id": [item["tile_id"] for item in items],
        }
    )
    return result


def grouped_sensor_collate(batch: Iterable[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    """Group a mixed native batch into same-sensor sub-batches.

    This is the hand-off format for the shared model: each present sensor is
    adapted separately, then all groups use the same YOLO26 backbone/head.
    """
    items = list(batch)
    if not items:
        raise ValueError("cannot collate an empty batch")
    groups: dict[str, list[dict[str, Any]]] = {"S1": [], "S2": []}
    for item in items:
        sensor = item["sensor"]
        if sensor not in groups:
            raise ValueError(f"unknown sensor in batch: {sensor!r}")
        groups[sensor].append(item)
    return {
        sensor: sturm_collate(sensor_items)
        for sensor, sensor_items in groups.items()
        if sensor_items
    }


def make_loader(
    manifest_path: str | Path,
    split_path: str | Path,
    split: str,
    *,
    sensor: str,
    batch_size: int = 4,
    shuffle: bool = False,
    num_workers: int = 0,
) -> DataLoader[dict[str, Any]]:
    """Create a deterministic same-sensor loader for unit/smoke validation."""
    dataset = SturmFloodDataset(
        manifest_path=manifest_path,
        split_path=split_path,
        split=split,
        sensor=sensor,
    )
    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        pin_memory=False,
        collate_fn=sturm_collate,
    )


def make_grouped_loader(
    manifest_path: str | Path,
    split_path: str | Path,
    split: str,
    *,
    batch_size: int = 4,
    shuffle: bool = False,
    num_workers: int = 0,
) -> DataLoader[dict[str, dict[str, Any]]]:
    """Create a mixed-sensor loader whose batches are grouped before adapting."""
    dataset = SturmFloodDataset(
        manifest_path=manifest_path,
        split_path=split_path,
        split=split,
        sensor=None,
    )
    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        pin_memory=False,
        collate_fn=grouped_sensor_collate,
    )
